"""Parallelism capability matrix (deliverable): what this vLLM build declares vs what was validated on gpu-02.

"Declared" = the flag exists in vLLM 0.31.0+cu126.abujafar1 (seen in a working launch command on the node).
"Validated" = served and benchmarked by us with 0 failed requests; evidence is computed from results.jsonl.

Run:  python -m planner.capabilities            -> writes results/capability-matrix.md and prints it
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

STRATEGIES = [
    # name, flag, labels that validate it, note
    ("Tensor parallel (TP)", "--tensor-parallel-size",
     ["qwen0.5b-tp2-v2", "qwen7b-tp2-v2", "qwen7b-tp4-v2"],
     "Pays off for 7B (1.6x at TP=2, 2.5x at TP=4 per token), not for 0.5B. CUSTOM all-reduce over NVLink."),
    ("Pipeline parallel (PP)", "--pipeline-parallel-size", ["qwen0.5b-pp2-v2"],
     "Slower per token (0.5B: 1.34x TPOT); cannot split the embedding. Memory model validated on 7B PP=2 (+1.8%)."),
    ("Data parallel (DP)", "--data-parallel-size", ["qwen0.5b-dp2-v2"],
     "Scales linearly with --api-server-count 2 and a 4-process client. Best under loose SLAs."),
    ("Expert parallel (EP)", "--enable-expert-parallel", [], "MoE only; owned with Student 4. Not run yet."),
    ("Expert load balancing (EPLB)", "--enable-eplb", [], "MoE only; Student 4."),
    ("Prefill context parallel", "--prefill-context-parallel-size", [], "Not run yet."),
    ("Decode context parallel", "--decode-context-parallel-size", [], "Not run yet."),
    ("Dual-batch overlap", "--enable-dbo", [], "Not run yet."),
    ("Prefill/decode disaggregation", "Dynamo 1.6 (dynamo.vllm)", [],
     "Dynamo 1.6 + NIXL present on the node (another user's stack); image has no nixl-cu12. Step 8."),
]


def summarise(rows: list[dict], label: str) -> dict:
    rs = [r for r in rows if r["label"] == label]
    if not rs:
        return {}
    c1 = next((r for r in rs if r["concurrency"] == 1), None)
    best = max(rs, key=lambda r: r["throughput_tok_s"])
    return {"model": rs[0]["model"].split("/")[-1], "requests": sum(r["requests"] for r in rs),
            "failed": sum(r["failed"] for r in rs), "tpot_c1": c1["tpot_p50_ms"] if c1 else None,
            "peak": best["throughput_tok_s"], "peak_conc": best["concurrency"]}


def build(path: str = "results/results.jsonl") -> list[dict]:
    rows = [json.loads(l) for l in Path(path).read_text().splitlines()]
    out = []
    for name, flag, labels, note in STRATEGIES:
        ev = [s | {"label": l} for l in labels if (s := summarise(rows, l))]
        ok = bool(ev) and all(e["failed"] == 0 for e in ev)
        out.append({"strategy": name, "flag": flag, "declared": True, "validated": ok, "evidence": ev, "note": note})
    return out


def to_markdown(matrix: list[dict]) -> str:
    lines = ["# Parallelism capability matrix (gpu-02, vLLM 0.31.0+cu126.abujafar1, A100-SXM4-80GB, NVSwitch)", "",
             "Generated by `python -m planner.capabilities` from `results/results.jsonl`.", "",
             "| Strategy | Flag | Declared | Validated on gpu-02 | Evidence | Notes |", "|---|---|---|---|---|---|"]
    for m in matrix:
        ev = "; ".join(f"{e['model']} `{e['label']}`: {e['requests']} req, {e['failed']} failed, "
                       f"TPOT@1 {e['tpot_c1']} ms, peak {e['peak']:,.0f} tok/s @{e['peak_conc']}" for e in m["evidence"])
        lines.append(f"| {m['strategy']} | `{m['flag']}` | yes | {'**yes**' if m['validated'] else 'no'} | "
                     f"{ev or '—'} | {m['note']} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    md = to_markdown(build())
    Path("results/capability-matrix.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
